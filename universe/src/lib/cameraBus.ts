/**
 * Канал команд к камере из интерфейса.
 *
 * Кнопки зума живут в DOM, а камера — внутри канваса. Гонять это через
 * состояние React нельзя: удержание кнопки зума меняет расстояние каждый
 * кадр, и перерисовка дерева на 60 Гц съела бы весь бюджет. Поэтому —
 * простой мутируемый объект, который камера читает в useFrame.
 */

export const cameraBus = {
  /**
   * Множитель расстояния, накопленный за кадр. 1 — ничего не делать,
   * меньше 1 — приблизиться, больше — отдалиться.
   */
  zoomFactor: 1,
  /** Признак, что зум идёт прямо сейчас (кнопка удерживается или пинч). */
  zooming: false,
  /**
   * Насколько пользователь «упирается» в предел масштаба, 0..1.
   * Интерфейс показывает по этому значению подсказку о переходе на
   * соседний уровень, чтобы переключение не выглядело случайным.
   */
  edgePressure: 0,
  /** В какую сторону упор: +1 наружу, −1 внутрь, 0 нет упора. */
  edgeDir: 0,
}

/** Запросить изменение расстояния камеры в `f` раз. */
export function requestZoom(f: number) {
  cameraBus.zoomFactor *= f
}
