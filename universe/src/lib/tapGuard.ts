/**
 * Отличает касание от перетаскивания.
 *
 * Зачем: и three.js, и DOM считают кликом любую пару «нажал — отпустил» на
 * одном элементе, независимо от того, сколько палец прошёл между ними.
 * На карте это ломает всё: пользователь ведёт пальцем, чтобы повернуть
 * камеру или смахнуть панель, палец начинает и заканчивает движение на
 * планете — и планета выбирается. Именно так панель фактов «сама
 * переключалась на другой объект»: закрыть её свайпом было невозможно,
 * потому что свайп тут же выбирал то, что было под пальцем.
 *
 * Решение: жест, прошедший больше порога, коротко запрещает выбор объектов.
 * Окно в 150 мс перекрывает промежуток между `pointerup` и синтетическим
 * `click`, но заканчивается задолго до следующего осознанного касания.
 */

/** Сколько пикселей суммарного смещения ещё считается касанием. */
export const TAP_SLOP_PX = 10

let suppressUntil = 0

/** Пометить, что жест был перетаскиванием, а не касанием. */
export function markDrag(): void {
  suppressUntil = performance.now() + 150
}

/** true, если прямо сейчас выбор объекта должен игнорироваться. */
export function selectionSuppressed(): boolean {
  return performance.now() < suppressUntil
}

/** Снять запрет досрочно — нужно для программного выбора (поиск, тесты). */
export function allowSelection(): void {
  suppressUntil = 0
}
